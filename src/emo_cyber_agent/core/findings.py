"""Finding Lifecycle & Security Classification — ECA-T011.

Evidence → Observation → Hypothesis → FindingCandidate → Verification
→ Finding. The path is never shortened: no CANDIDATE → CONFIRMED jump
without verification evidence, no CANDIDATE → REPORTED without
eligibility, and no model text ever becomes a Finding directly.

A Finding is an Evidence-backed, Verification-backed, Core-governed,
auditable security record — never prose generated by a model.
"""

from __future__ import annotations

import hashlib
from datetime import datetime, timezone
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator

from emo_cyber_agent.core.correlation import FindingCandidate
from emo_cyber_agent.core.verification import assess_candidate  # verification-level assessment, re-exported for the finding path

__all__ = ["assess_candidate"]

CLASSIFICATION_VERSION = "cls-v1"
FINDING_SCHEMA_VERSION = "0.1.0"


class FindingStatus(StrEnum):
    CANDIDATE = "candidate"
    TRIAGED = "triaged"
    VERIFIED = "verified"
    CONFIRMED = "confirmed"
    REPORTED = "reported"
    RESOLVED = "resolved"
    DISPUTED = "disputed"
    REFUTED = "refuted"
    SUPPRESSED = "suppressed"
    DUPLICATE = "duplicate"
    INCONCLUSIVE = "inconclusive"


class Severity(StrEnum):
    INFO = "info"
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class FindingTaxonomy(StrEnum):
    AUTHENTICATION = "authentication"
    AUTHORIZATION = "authorization"
    INJECTION = "injection"
    CRYPTOGRAPHY = "cryptography"
    SECRETS = "secrets"
    DEPENDENCY = "dependency"
    SUPPLY_CHAIN = "supply_chain"
    DATA_EXPOSURE = "data_exposure"
    CONFIGURATION = "configuration"
    API_SECURITY = "api_security"
    RLS = "rls"
    BUSINESS_LOGIC = "business_logic"
    INFRASTRUCTURE = "infrastructure"
    SESSION = "session"
    INPUT_VALIDATION = "input_validation"
    OTHER = "other"


class Eligibility(StrEnum):
    ELIGIBLE = "eligible"
    NOT_ELIGIBLE = "not_eligible"
    NEEDS_REVIEW = "needs_review"


# Lifecycle: forward flow plus explicit alternative terminals. No shortcuts.
_FINDING_TRANSITIONS: dict[FindingStatus, frozenset[FindingStatus]] = {
    FindingStatus.CANDIDATE: frozenset({FindingStatus.TRIAGED, FindingStatus.DUPLICATE, FindingStatus.INCONCLUSIVE}),
    FindingStatus.TRIAGED: frozenset({FindingStatus.VERIFIED, FindingStatus.DISPUTED, FindingStatus.SUPPRESSED, FindingStatus.DUPLICATE, FindingStatus.INCONCLUSIVE}),
    FindingStatus.VERIFIED: frozenset({FindingStatus.CONFIRMED, FindingStatus.REFUTED, FindingStatus.DISPUTED, FindingStatus.INCONCLUSIVE}),
    FindingStatus.CONFIRMED: frozenset({FindingStatus.REPORTED, FindingStatus.DISPUTED, FindingStatus.RESOLVED}),
    FindingStatus.REPORTED: frozenset({FindingStatus.RESOLVED, FindingStatus.DISPUTED, FindingStatus.SUPPRESSED}),
    FindingStatus.RESOLVED: frozenset(),
    FindingStatus.DISPUTED: frozenset({FindingStatus.TRIAGED, FindingStatus.VERIFIED, FindingStatus.INCONCLUSIVE}),
    FindingStatus.REFUTED: frozenset(),
    FindingStatus.SUPPRESSED: frozenset({FindingStatus.TRIAGED}),
    FindingStatus.DUPLICATE: frozenset(),
    FindingStatus.INCONCLUSIVE: frozenset({FindingStatus.TRIAGED}),
}


def transition_finding(current: FindingStatus, new: FindingStatus) -> FindingStatus:
    if new not in _FINDING_TRANSITIONS[current]:
        raise ValueError(f"invalid finding transition {current.value} → {new.value}")
    return new


class SeverityAssessment(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    severity: Severity
    basis: str = Field(..., min_length=1)
    source: str = Field(..., min_length=1)
    rule_version: str = Field(default=CLASSIFICATION_VERSION)
    assessed_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class ConfidenceAssessment(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    value: float = Field(..., ge=0.0, le=1.0)
    evidence_count: int = Field(default=0, ge=0)
    independent_sources: int = Field(default=0, ge=0)
    verification_strength: str = ""
    contradiction_present: bool = False
    basis: str = ""


class Classification(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    category: FindingTaxonomy
    severity: SeverityAssessment
    confidence: ConfidenceAssessment
    cwe: str | None = None
    owasp: str | None = None
    cvss_vector: str | None = None
    cvss_score: float | None = Field(default=None, ge=0.0, le=10.0)
    cvss_source: str | None = None
    classification_version: str = Field(default=CLASSIFICATION_VERSION)
    explained: str = ""


class ClassificationConflict(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    assessments: tuple[SeverityAssessment, ...]
    note: str = ""


class Remediation(BaseModel):
    """Structured recommendation DATA. Never executed by Core."""

    model_config = ConfigDict(frozen=True, extra="forbid")
    recommendation: str = Field(..., min_length=1)
    affected_component: str = ""
    remediation_type: str = ""
    validation_guidance: str = ""


class SuppressionRecord(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    reason: str = Field(..., min_length=1)
    actor: str = Field(..., min_length=1)  # human/policy/system — never model
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    scope: str = ""
    expires_at: str | None = None

    @field_validator("actor")
    @classmethod
    def _no_model_actor(cls, v: str) -> str:
        if v.strip().lower() in ("model", "llm", "reasoner", "ai"):
            raise ValueError("model cannot suppress findings")
        return v


class SecurityFinding(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    finding_id: str = Field(..., min_length=1)
    audit_id: str = Field(..., min_length=1)
    asset_id: str | None = None
    title: str = Field(..., min_length=1)
    description: str = Field(..., min_length=1)
    category: FindingTaxonomy
    severity: Severity
    confidence: float = Field(..., ge=0.0, le=1.0)
    status: FindingStatus = FindingStatus.CANDIDATE
    cwe: str | None = None
    owasp: str | None = None
    affected_locations: tuple[str, ...] = ()
    evidence_ids: tuple[str, ...] = ()
    observation_ids: tuple[str, ...] = ()
    candidate_id: str = Field(..., min_length=1)
    verification_ids: tuple[str, ...] = ()
    first_seen: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    last_seen: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    provenance: dict[str, Any] = Field(default_factory=dict)
    remediation: Remediation | None = None
    references: tuple[str, ...] = ()
    suppression: SuppressionRecord | None = None
    # root-cause separation: unknown impact stays UNASSESSED, never invented
    observed_issue: str = ""
    root_cause: str = ""
    impact: str = "UNASSESSED"
    attack_precondition: str = ""
    fingerprint: str = ""
    regression_key: str = ""

    def transition_to(self, new: FindingStatus) -> SecurityFinding:
        transition_finding(self.status, new)
        return SecurityFinding(**{**self.model_dump(), "status": new, "last_seen": datetime.now(timezone.utc).isoformat()})


# ---------------------------------------------------------------------------
# Identity & dedup (audit-bound; regression keys link history only)
# ---------------------------------------------------------------------------

def finding_fingerprint(*, audit_id: str, asset_id: str | None, category: str, location: str, identity: str, rule: str) -> str:
    base = "|".join([audit_id, asset_id or "", category, location, identity, rule])
    return hashlib.sha256(base.encode("utf-8", errors="replace")).hexdigest()


def regression_key(*, asset_id: str | None, category: str, location: str, identity: str, rule: str) -> str:
    """Cross-audit history link. Carries NO evidence and merges nothing."""
    base = "|".join(["regression", asset_id or "", category, location, identity, rule])
    return hashlib.sha256(base.encode("utf-8", errors="replace")).hexdigest()


class FindingStore:
    """Audit-scoped finding registry with deterministic dedup."""

    def __init__(self) -> None:
        self._items: dict[str, SecurityFinding] = {}
        self._audit_of: dict[str, str] = {}
        self._by_fingerprint: dict[str, str] = {}

    def add(self, finding: SecurityFinding) -> SecurityFinding:
        """Dedup within one audit: same fingerprint returns the ORIGINAL as
        canonical and records the newcomer as DUPLICATE (never merged)."""
        if not finding.evidence_ids:
            raise ValueError("finding without evidence denied")
        existing_id = self._by_fingerprint.get(finding.fingerprint)
        if existing_id is not None and self._audit_of.get(existing_id) == finding.audit_id:
            canonical = self._items[existing_id]
            dup = SecurityFinding(**{**finding.model_dump(), "status": FindingStatus.DUPLICATE, "provenance": {**finding.provenance, "duplicate_of": existing_id}})
            self._items[dup.finding_id] = dup
            self._audit_of[dup.finding_id] = dup.audit_id
            return canonical
        self._items[finding.finding_id] = finding
        self._audit_of[finding.finding_id] = finding.audit_id
        if finding.fingerprint:
            self._by_fingerprint[finding.fingerprint] = finding.finding_id
        return finding

    def get(self, finding_id: str, *, audit_id: str) -> SecurityFinding:
        if self._audit_of.get(finding_id) != audit_id:
            raise KeyError(f"finding not in audit scope: {finding_id}")
        return self._items[finding_id]

    def list(self, *, audit_id: str) -> list[SecurityFinding]:
        return [f for fid, f in self._items.items() if self._audit_of.get(fid) == audit_id]


