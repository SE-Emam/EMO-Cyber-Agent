class EligibilityResult(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")
    verdict: Eligibility
    reasons: tuple[str, ...] = ()


def evaluate_finding_eligibility(
    *,
    candidate: FindingCandidate,
    evidence_ids: list[str],
    provenance_ok: bool,
    scope_ok: bool,
    verification_status: str,
    contradiction_unresolved: bool,
    candidate_status: str,
    policy_ok: bool,
    min_evidence: int = 1,
) -> EligibilityResult:
    reasons: list[str] = []
    if len(evidence_ids) < min_evidence:
        reasons.append("missing-evidence")
    if not provenance_ok:
        reasons.append("invalid-provenance")
    if not scope_ok:
        reasons.append("scope-mismatch")
    if verification_status not in ("confirmed", "supported"):
        reasons.append("unverified-candidate")
    if contradiction_unresolved:
        reasons.append("unresolved-contradiction")
    if candidate_status not in ("correlated", "supported", "verifying", "needs_verification"):
        reasons.append("bad-candidate-state")
    if not policy_ok:
        reasons.append("policy-denied")
    if not reasons:
        return EligibilityResult(verdict=Eligibility.ELIGIBLE, reasons=("criteria-met",))
    if set(reasons) <= {"unverified-candidate"}:
        return EligibilityResult(verdict=Eligibility.NEEDS_REVIEW, reasons=tuple(reasons))
    return EligibilityResult(verdict=Eligibility.NOT_ELIGIBLE, reasons=tuple(reasons))


# ---------------------------------------------------------------------------
# Deterministic classification (rules cls-v1; model suggests, Core decides)
# ---------------------------------------------------------------------------

_SEVERITY_ORDER = ["info", "low", "medium", "high", "critical"]

# Sparse static maps with recorded provenance. Unknown → null (never invented).
CWE_MAP: dict[str, str] = {
    "R1-auth-weakness": "CWE-639",
    "R3-secret-exposure": "CWE-798",
}
OWASP_MAP: dict[str, str] = {
    "R1-auth-weakness": "A01:2021-Broken Access Control",
    "R3-secret-exposure": "A07:2021-Identification and Authentication Failures",
}
TAXONOMY_MAP: dict[str, FindingTaxonomy] = {
    "R1-auth-weakness": FindingTaxonomy.AUTHORIZATION,
    "R2-vuln-dependency": FindingTaxonomy.DEPENDENCY,
    "R3-secret-exposure": FindingTaxonomy.SECRETS,
    "R4-access-control-risk": FindingTaxonomy.RLS,
}


def _downgrade(sev: str) -> str:
    order = _SEVERITY_ORDER
    return order[max(0, order.index(sev) - 1)] if sev in order else sev


def classify_candidate(
    *,
    candidate: FindingCandidate,
    verification_status: str,
    scanner_severities: list[str],
    evidence_count: int,
    independent_sources: int,
    contradiction: bool,
    cvss: dict[str, Any] | None = None,
) -> tuple[Classification, ClassificationConflict | None]:
    """Deterministic severity/confidence. Scanner severities are data:
    unanimously-lower + supported-only ⇒ one-level downgrade with reason;
    conflicting scanner severities ⇒ conflict + NEEDS_REVIEW (no auto-pick)."""
    from emo_cyber_agent.core.correlation import compute_confidence

    rule = candidate.rule_id.split("@")[0] if "@" in candidate.rule_id else candidate.rule_id
    provisional = candidate.provisional_severity if candidate.provisional_severity in _SEVERITY_ORDER else "info"
    uniq_scanner = sorted({s.lower() for s in scanner_severities if s})
    conflict = None
    final_sev = provisional
    basis = f"candidate provisional {provisional} + {verification_status} verification (cls-v1)"
    if len(uniq_scanner) > 1:
        conflict = ClassificationConflict(
            assessments=tuple(SeverityAssessment(severity=Severity(s) if s in _SEVERITY_ORDER else Severity.INFO, basis=f"scanner-attributed {s}", source="scanner") for s in uniq_scanner),
            note="conflicting scanner severities kept; needs review, no auto-pick",
        )
        basis += "; scanner conflict recorded, provisional kept pending review"
    elif (
        len(uniq_scanner) == 1
        and uniq_scanner[0] in _SEVERITY_ORDER
        and provisional in _SEVERITY_ORDER
        and verification_status == "supported"
        and _SEVERITY_ORDER.index(uniq_scanner[0]) < _SEVERITY_ORDER.index(provisional)
    ):
        final_sev = _downgrade(provisional)
        basis += f"; unanimous scanner {uniq_scanner[0]} below provisional with supported-only verification → downgraded with reason"
    value = compute_confidence(n_evidence=evidence_count, n_sources=independent_sources, has_conflict=contradiction)
    if verification_status == "confirmed":
        value = round(min(0.95, value + 0.1), 2)
    classification = Classification(
        category=TAXONOMY_MAP.get(rule, FindingTaxonomy.OTHER),
        severity=SeverityAssessment(severity=Severity(final_sev), basis=basis, source="core-classification", rule_version=CLASSIFICATION_VERSION),
        confidence=ConfidenceAssessment(value=value, evidence_count=evidence_count, independent_sources=independent_sources, verification_strength=verification_status, contradiction_present=contradiction, basis="evidence count + sources + verification + conflict (no model scores)"),
        cwe=CWE_MAP.get(rule),
        owasp=OWASP_MAP.get(rule),
        cvss_vector=(cvss or {}).get("vector"),
        cvss_score=(cvss or {}).get("score"),
        cvss_source=(cvss or {}).get("source"),
        explained=f"severity {final_sev}: {basis}; evidence {[candidate.candidate_id]}; verification {verification_status}; rule {rule}@{CLASSIFICATION_VERSION}",
    )
    return classification, conflict


# ---------------------------------------------------------------------------
# Promotion: candidate + verification + classification → SecurityFinding
# ---------------------------------------------------------------------------

def promote_candidate(
    *,
    candidate: FindingCandidate,
    verification_status: str,
    verification_ids: list[str] | tuple[str, ...],
    evidence_ids: list[str] | tuple[str, ...],
    observation_ids: list[str] | tuple[str, ...],
    classification: Classification,
    scope_ok: bool,
    policy_ok: bool,
    audit_id: str,
    asset_id: str | None = None,
    location: str = "",
    identity: str = "",
    remediation: Remediation | None = None,
    references: list[str] | tuple[str, ...] | None = None,
) -> SecurityFinding:
    """Builds a CONFIRMED finding ONLY through the gated path. Any shortcut
    raises instead of producing a weaker object."""
    transition_candidate_state(candidate.status, "confirmed-target")
    elig = evaluate_finding_eligibility(
        candidate=candidate, evidence_ids=list(evidence_ids), provenance_ok=True, scope_ok=scope_ok,
        verification_status=verification_status, contradiction_unresolved=False,
        candidate_status=candidate.status.value, policy_ok=policy_ok,
    )
    if elig.verdict != Eligibility.ELIGIBLE:
        raise ValueError(f"candidate not eligible: {elig.reasons}")
    fp = finding_fingerprint(audit_id=audit_id, asset_id=asset_id, category=classification.category.value, location=location, identity=identity or candidate.candidate_id, rule=candidate.rule_id)
    return SecurityFinding(
        finding_id=f"finding-{candidate.candidate_id[:8]}-{fp[:8]}",
        audit_id=audit_id,
        asset_id=asset_id,
        title=candidate.hypothesis[:200],
        description=candidate.hypothesis[:2000],
        category=classification.category,
        severity=classification.severity.severity,
        confidence=classification.confidence.value,
        status=FindingStatus.CONFIRMED,
        cwe=classification.cwe,
        owasp=classification.owasp,
        affected_locations=tuple([location] if location else []),
        evidence_ids=tuple(evidence_ids),
        observation_ids=tuple(observation_ids),
        candidate_id=candidate.candidate_id,
        verification_ids=tuple(verification_ids),
        provenance={"candidate": candidate.candidate_id, "rule": candidate.rule_id, "classification_version": CLASSIFICATION_VERSION, "finding_schema": FINDING_SCHEMA_VERSION, "policy": "strict"},
        remediation=remediation,
        references=tuple(references or []),
        observed_issue=candidate.hypothesis[:500],
        root_cause="",
        impact="UNASSESSED",
        attack_precondition="",
        fingerprint=fp,
        regression_key=regression_key(asset_id=asset_id, category=classification.category.value, location=location, identity=identity or candidate.candidate_id, rule=candidate.rule_id),
    )


def transition_candidate_state(current: str, target: str) -> str:
    """Maps ECA-T008 candidate statuses onto the gated promotion pre-path.

    Only these pre-states may ENTER verification-driven promotion; the
    CONFIRMED state itself is produced solely by promote_candidate.
    """
    allowed = {"correlated", "supported", "verifying", "needs_verification"}
    if target != "confirmed-target":
        raise ValueError(f"unknown promotion target: {target}")
    if current not in allowed:
        raise ValueError(f"candidate state {current} cannot enter confirmation")
    return target


def apply_model_suggestion(finding: SecurityFinding, suggestion: dict[str, Any]) -> SecurityFinding:
    """Model suggestions land as UNVERIFIED annotations only. Core-decided
    severity/status/evidence/scope are immutable through this path."""
    for locked in ("severity", "status", "evidence_ids", "audit_id", "candidate_id", "verification_ids", "fingerprint"):
        if locked in suggestion:
            raise ValueError(f"model cannot set {locked}")
    allowed = {k: v for k, v in suggestion.items() if k in ("title", "description", "remediation", "references", "cwe", "owasp")}
    if "cwe" in allowed and finding.cwe is not None:
        raise ValueError("model cannot override Core CWE")
    if "owasp" in allowed and finding.owasp is not None:
        raise ValueError("model cannot override Core OWASP")
    data = finding.model_dump()
    for k, v in allowed.items():
        data[k] = v
    data["provenance"] = {**finding.provenance, "model_suggestion": "unverified"}
    return SecurityFinding(**data)


def is_reportable(finding: SecurityFinding) -> tuple[bool, list[str]]:
    problems: list[str] = []
    if not finding.evidence_ids:
        problems.append("missing-evidence")
    if not finding.provenance:
        problems.append("invalid-provenance")
    if not finding.audit_id or not finding.candidate_id:
        problems.append("missing-scope")
    if finding.status not in (FindingStatus.CONFIRMED, FindingStatus.REPORTED):
        problems.append("unverified-candidate")
    if not finding.fingerprint:
        problems.append("malformed-identity")
    return (not problems, problems)
